"""tests/unit/test_inferred_tests.py

Which inferred staging tests block (key columns) and which warn (everything else).
"""

from __future__ import annotations

from pathlib import Path

import pytest

from dango.utils.inferred_tests import (
    has_not_null_test,
    inferred_not_null_test,
    is_customized_model,
    is_key_column,
)

WARN = {"not_null": {"config": {"severity": "warn"}}}


@pytest.mark.unit
@pytest.mark.parametrize("name", ["id", "ID", "uuid", "key"])
def test_key_names_get_blocking_not_null(name: str) -> None:
    assert is_key_column(name)
    assert inferred_not_null_test(name) == "not_null"


@pytest.mark.unit
@pytest.mark.parametrize("name", ["customer_id", "status", "identity", "keyword", "order"])
def test_other_columns_get_warn_only_not_null(name: str) -> None:
    assert not is_key_column(name)
    assert inferred_not_null_test(name) == WARN


@pytest.mark.unit
def test_warn_form_counts_as_existing_not_null() -> None:
    assert has_not_null_test([WARN])
    assert has_not_null_test(["not_null"])
    assert not has_not_null_test(["unique"])


@pytest.mark.unit
def test_customized_model_detection(tmp_path: Path) -> None:
    assert not is_customized_model(tmp_path, "stg_a__t")  # no SQL file: not customized
    sql = tmp_path / "stg_a__t.sql"
    sql.write_text("-- Auto-generated by Dango on now\nselect 1\n", encoding="utf-8")
    assert not is_customized_model(tmp_path, "stg_a__t")
    sql.write_text("-- mine\nselect 1\n", encoding="utf-8")
    assert is_customized_model(tmp_path, "stg_a__t")
