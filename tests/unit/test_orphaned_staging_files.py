"""tests/unit/test_orphaned_staging_files.py

`dango validate` and `dango db clean` list generated staging files whose source is no longer
configured, with the exact delete command, and delete nothing themselves.
"""

from __future__ import annotations

import os
import re
from pathlib import Path
from typing import Any

import duckdb
import pytest
import yaml
from click.testing import CliRunner

from dango.cli.main import cli
from dango.cli.validate import ProjectValidator

pytestmark = pytest.mark.unit

_ANSI = re.compile(r"\x1b\[[0-9;]*m")
STAGING = Path("dbt") / "models" / "staging"
GENERATED_SQL = "-- Auto-generated by Dango on 2026-01-01\nselect 1\n"
GENERATED_YML = "# Auto-generated by Dango on 2026-01-01\nversion: 2\n"

ORPHANS = [
    "dbt/models/staging/sources_sales.yml",
    "dbt/models/staging/stg_sales.yml",
    "dbt/models/staging/stg_sales__sales.sql",
]


def _local(name: str) -> dict[str, Any]:
    return {"name": name, "type": "local_files", "local_files": {"directory": f"data/{name}"}}


def _project(root: Path, configured: list[str]) -> Path:
    dango = root / ".dango"
    dango.mkdir(parents=True, exist_ok=True)
    (dango / "project.yml").write_text(
        yaml.safe_dump({"project": {"name": "t", "created_by": "x@y.z", "purpose": "testing"}}),
        encoding="utf-8",
    )
    (dango / "sources.yml").write_text(
        yaml.safe_dump({"version": "1.0", "sources": [_local(n) for n in configured]}),
        encoding="utf-8",
    )
    return root


def _stage(root: Path, name: str, text: str) -> Path:
    path = root / STAGING / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


def _generated_files(root: Path, source: str) -> list[Path]:
    return [
        _stage(root, f"sources_{source}.yml", GENERATED_YML),
        _stage(root, f"stg_{source}.yml", GENERATED_YML),
        _stage(root, f"stg_{source}__{source}.sql", GENERATED_SQL),
    ]


def _expected_lines(paths: list[str]) -> list[str]:
    """The delete command as printed: one `rm` line, or one `del "<path>"` per file on Windows."""
    if os.name == "nt":
        return [f'del "{p.replace("/", chr(92))}"' for p in paths]
    return ["rm " + " ".join(paths)]


def _assert_command(text: str) -> None:
    for line in _expected_lines(ORPHANS):
        assert line in text, text


def find_orphaned_staging_files(root: Path, configured: list[str]) -> list[Path]:
    from dango.config.source_checks import find_orphaned_staging_files as find

    return find(root, configured)


def _flat(text: str) -> str:
    return " ".join(_ANSI.sub("", text).split())


@pytest.fixture(autouse=True)
def _isolate(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    monkeypatch.setenv("PYTHON_KEYRING_BACKEND", "keyring.backends.fail.Keyring")
    monkeypatch.setenv("HOME", str(tmp_path / "home"))
    monkeypatch.setenv("USERPROFILE", str(tmp_path / "home"))


class TestFindOrphanedStagingFiles:
    def test_files_of_a_removed_source_are_found_and_configured_ones_are_not(
        self, tmp_path: Path
    ) -> None:
        _generated_files(tmp_path, "sales")
        _generated_files(tmp_path, "sales2")

        found = find_orphaned_staging_files(tmp_path, ["sales2"])

        assert [p.as_posix() for p in found] == ORPHANS

    def test_a_generated_geo_names_model_belongs_to_its_source(self, tmp_path: Path) -> None:
        _stage(tmp_path, "stg_ads__geo_names.sql", "-- Auto-generated by Dango\nselect 1\n")

        assert find_orphaned_staging_files(tmp_path, ["ads"]) == []
        assert [p.name for p in find_orphaned_staging_files(tmp_path, [])] == [
            "stg_ads__geo_names.sql"
        ]

    def test_hand_written_files_are_never_listed(self, tmp_path: Path) -> None:
        _stage(tmp_path, "stg_mine__orders.sql", "select 1\n")
        _stage(tmp_path, "stg_mine.yml", "version: 2\n")
        _stage(tmp_path, "notes.md", "# x\n")

        assert find_orphaned_staging_files(tmp_path, []) == []

    def test_a_source_name_containing_a_double_underscore_is_not_misattributed(
        self, tmp_path: Path
    ) -> None:
        _stage(tmp_path, "stg_a__b__t.sql", GENERATED_SQL)

        assert find_orphaned_staging_files(tmp_path, ["a__b"]) == []

    def test_no_staging_directory_is_fine(self, tmp_path: Path) -> None:
        assert find_orphaned_staging_files(tmp_path, ["sales"]) == []


class TestDeleteCommand:
    def test_windows_command_is_one_del_per_path_so_powershell_runs_it(self) -> None:
        from dango.config.source_checks import delete_command

        command = delete_command([Path(p) for p in ORPHANS], windows=True)

        assert command.split("\n") == [f'del "{p.replace("/", chr(92))}"' for p in ORPHANS]

    def test_posix_command_is_a_single_rm(self) -> None:
        from dango.config.source_checks import delete_command

        command = delete_command([Path(p) for p in ORPHANS], windows=False)

        assert command == "rm " + " ".join(ORPHANS)


class TestValidateListsOrphans:
    def test_validate_warns_with_the_files_and_the_exact_command_and_deletes_nothing(
        self, tmp_path: Path
    ) -> None:
        root = _project(tmp_path, ["sales2"])
        files = _generated_files(root, "sales") + _generated_files(root, "sales2")
        validator = ProjectValidator(root)

        validator._check_orphaned_staging()

        rows = [r for r in validator.results if r.name == "Staging files"]
        assert len(rows) == 1 and rows[0].status == "warn"
        for path in ORPHANS:
            assert path in rows[0].message
        assert rows[0].command == "\n".join(_expected_lines(ORPHANS))
        assert "sales2" not in rows[0].message
        assert all(f.exists() for f in files)

    def test_validate_prints_the_command_unwrapped_below_the_table(self, tmp_path: Path) -> None:
        from dango.cli.validate import console

        root = _project(tmp_path, ["sales2"])
        _generated_files(root, "sales")
        validator = ProjectValidator(root)
        validator._check_orphaned_staging()

        with console.capture() as captured:
            validator._display_results()

        lines = [line.strip() for line in _ANSI.sub("", captured.get()).splitlines()]
        for expected in _expected_lines(ORPHANS):
            assert expected in lines, lines

    def test_bracket_text_in_a_file_name_is_shown_not_swallowed(self, tmp_path: Path) -> None:
        from dango.cli.validate import console

        root = _project(tmp_path, ["sales"])
        _stage(root, "sources_a[b].yml", GENERATED_YML)
        _stage(root, "stg_a[bold]__t.sql", GENERATED_SQL)
        validator = ProjectValidator(root)
        validator._check_orphaned_staging()

        with console.capture() as captured:
            validator._display_results()

        text = _flat(captured.get())
        assert "sources_a[b].yml" in text and "stg_a[bold]__t.sql" in text

    def test_validate_is_quiet_when_every_staging_file_has_a_source(self, tmp_path: Path) -> None:
        root = _project(tmp_path, ["sales"])
        _generated_files(root, "sales")
        validator = ProjectValidator(root)

        validator._check_orphaned_staging()

        assert validator.results == []


class TestDbClean:
    def test_db_clean_lists_orphans_when_there_is_nothing_else_to_clean(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        root = _project(tmp_path, ["sales2"])
        files = _generated_files(root, "sales") + _generated_files(root, "sales2")
        db = root / "data" / "warehouse.duckdb"
        db.parent.mkdir(parents=True)
        conn = duckdb.connect(str(db))
        conn.execute("CREATE SCHEMA raw_sales2")
        conn.execute("CREATE TABLE raw_sales2.sales2 (id INTEGER)")
        conn.close()
        monkeypatch.chdir(root)

        result = CliRunner().invoke(cli, ["db", "clean", "--yes"])

        text = _flat(result.output)
        assert result.exit_code == 0, text
        assert "No orphaned tables" in text
        for path in ORPHANS:
            assert path in text
        _assert_command(text)
        assert all(f.exists() for f in files)

    def test_db_clean_still_drops_orphan_tables_and_lists_staging_files(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        root = _project(tmp_path, ["sales2"])
        files = _generated_files(root, "sales")
        db = root / "data" / "warehouse.duckdb"
        db.parent.mkdir(parents=True)
        conn = duckdb.connect(str(db))
        conn.execute("CREATE SCHEMA raw_sales")
        conn.execute("CREATE TABLE raw_sales.sales (id INTEGER)")
        conn.close()
        monkeypatch.chdir(root)

        result = CliRunner().invoke(cli, ["db", "clean", "--yes"])

        text = _flat(result.output)
        assert result.exit_code == 0, text
        assert "Dropped raw_sales.sales" in text
        _assert_command(text)
        assert all(f.exists() for f in files)

    def test_db_clean_without_a_database_still_lists_orphans(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        root = _project(tmp_path, ["sales2"])
        _generated_files(root, "sales")
        monkeypatch.chdir(root)

        result = CliRunner().invoke(cli, ["db", "clean", "--yes"])

        _assert_command(_flat(result.output))

    def test_db_clean_shows_bracket_text_in_a_file_name_as_written(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        root = _project(tmp_path, ["sales"])
        _stage(root, "sources_a[b].yml", GENERATED_YML)
        _stage(root, "stg_a[bold]__t.sql", GENERATED_SQL)
        monkeypatch.chdir(root)

        result = CliRunner().invoke(cli, ["db", "clean", "--yes"])

        text = _flat(result.output)
        assert result.exit_code == 0, text
        assert "sources_a[b].yml" in text and "stg_a[bold]__t.sql" in text

    def test_db_clean_prints_no_orphan_section_when_all_sources_are_configured(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        root = _project(tmp_path, ["sales"])
        _generated_files(root, "sales")
        monkeypatch.chdir(root)

        result = CliRunner().invoke(cli, ["db", "clean", "--yes"])

        assert "rm " not in _flat(result.output) and "del " not in _flat(result.output)
