const assert = require('node:assert/strict');
const fs = require('node:fs');
const {createRequire} = require('node:module');
const rq = createRequire('/work/deploy/package.json');
const {DuckDBInstance, version} = rq('@duckdb/node-api');
const {Client} = rq('pg');
const secrets = JSON.parse(fs.readFileSync('/secrets/catalog.json', 'utf8'));
const escape = value => value.replaceAll("'", "''");
(async () => {
    assert.match(version(), /^v?2\./);
    const instance = await DuckDBInstance.create(':memory:', {memory_limit: '1536MB', threads: '2'});
    const connection = await instance.connect();
    await connection.run('LOAD postgres_scanner');
    await connection.run('LOAD ducklake');
    await connection.run(`ATTACH 'ducklake:postgres:host=127.0.0.1 port=5432 dbname=probe user=postgres password=${escape(secrets.adminPassword)}' AS producer (DATA_PATH '/fixture/data', DUCKLAKE_VERSION '1.1', AUTOMATIC_MIGRATION FALSE, DATA_INLINING_ROW_LIMIT 0)`);
    await connection.run('CREATE SCHEMA producer.sales');
    await connection.run('CREATE TABLE producer.sales.orders (id INTEGER, amount INTEGER)');
    await connection.run('INSERT INTO producer.sales.orders VALUES (1, 100), (2, 200), (3, 50)');
    const total = await connection.runAndReadAll('SELECT SUM(amount)::INTEGER AS total FROM producer.sales.orders');
    assert.equal(Number(total.getRowObjects()[0].total), 350);
    await connection.run('DETACH producer'); connection.closeSync(); instance.closeSync();
    const pg = new Client({host:'127.0.0.1', port:5432, database:'probe', user:'postgres', password:secrets.adminPassword});
    await pg.connect();
    const spec = await pg.query("SELECT value FROM ducklake_metadata WHERE key = 'version'");
    assert.equal(spec.rows[0].value, '1.1');
    await pg.query(`CREATE ROLE probe_reader LOGIN PASSWORD '${escape(secrets.readerPassword)}'`);
    await pg.query('GRANT CONNECT ON DATABASE probe TO probe_reader');
    await pg.query('GRANT USAGE ON SCHEMA public TO probe_reader');
    await pg.query('GRANT SELECT ON ALL TABLES IN SCHEMA public TO probe_reader');
    await pg.query('ALTER ROLE probe_reader SET default_transaction_read_only = on');
    await pg.end();
    console.log(JSON.stringify({producerOnly: true, nativeConsumerEvidence: false, engineVersion: version(), catalogSpec: spec.rows[0].value, expectedTotal: 350}));
})().catch(error => { console.log(JSON.stringify({status:'FAIL', message:Object.values(secrets).some(value => String(error).includes(value)) ? '[SECRET EXPOSURE DETECTED; raw withheld]' : String(error)})); process.exitCode=1; });
