_VALID_MODEL_NAME_RE = re.compile(r"^[a-z][a-z0-9_]*$")  # same rule as commands/model.py
_AUTOGEN_MARKER = "-- Auto-generated by Dango"


def parse_project(project_root: Path) -> tuple[bool, str]:
    """Run ``dbt parse`` (no DuckDB writes, so no DbtLock); returns (ok, combined output)."""
    from dango.transformation import _dbt_telemetry_env, _get_dbt_executable

    dbt_dir = project_root / "dbt"
    try:
        result = subprocess.run(
            [
                _get_dbt_executable(),
                "parse",
                "--project-dir",
                str(dbt_dir),
                "--profiles-dir",
                str(dbt_dir),
            ],
            cwd=str(project_root),
            capture_output=True,
            stdin=subprocess.DEVNULL,  # never inherit the MCP server's JSON-RPC stdin
            text=True,
            timeout=30,
            env=_dbt_telemetry_env(),
        )
        return result.returncode == 0, (result.stdout or "") + (result.stderr or "")
    except subprocess.TimeoutExpired:
        return False, "dbt parse timed out after 30 seconds"
    except Exception as e:  # noqa: BLE001
        return False, f"dbt parse could not run: {e}"


class _Snapshot:
    """Remembers prior bytes of files (None = absent) so a failed change can be undone."""

    def __init__(self) -> None:
        self._prior: dict[Path, bytes | None] = {}

    def take(self, path: Path) -> None:
        """Record path's current bytes (once)."""
        if path not in self._prior:
            self._prior[path] = path.read_bytes() if path.exists() else None

    def restore(self) -> None:
        """Put every recorded file back (delete files that did not exist)."""
        for path, content in self._prior.items():
            if content is None:
                path.unlink(missing_ok=True)
            else:
                path.write_bytes(content)


def _check_upstream_exists(project_root: Path, upstream: list[str]) -> list[str]:
    known = (
        set(list_models(project_root))
        | stems(project_root, "seeds", "*.csv")
        | stems(project_root, "snapshots", "*.sql")
    )
    return [f"upstream model '{u}' does not exist" for u in upstream if u not in known]


def _apply(
    project_root: Path,
    result: ModelChangeResult,
    sql_path: Path,
    content: str | None,
    layer: str,
    name: str,
    description: str | None,
    columns: list[dict[str, Any]] | None,
    parse: bool,
) -> None:
    """Write sql + docs with a parse gate: roll back if dbt parse newly fails."""
    baseline_ok: bool | None = None
    if parse:
        baseline_ok, _ = parse_project(project_root)

    snap = _Snapshot()
    snap.take(sql_path)
    docs_wanted = description is not None or bool(columns)
    if docs_wanted:
        snap.take(resolve_docs_path(project_root, layer, name))
    try:
        if content is not None:
            sql_path.parent.mkdir(parents=True, exist_ok=True)
            sql_path.write_text(content)
            result.files_changed.append(rel_path(project_root, sql_path))
        if docs_wanted:
            docs_rel = upsert_model_docs(
                project_root, layer, name, description=description, columns=columns
            )
            if docs_rel:
                result.files_changed.append(docs_rel)
    except BaseException:
        snap.restore()
        raise

    if not parse:
        return
    if baseline_ok is False:
        result.parse_ok = False
        result.warnings.append("project already fails dbt parse before this change")
        return
    ok, out = parse_project(project_root)
    result.parse_ok = ok
    if not ok:
        snap.restore()
        raise ModelServiceError(
            [f"dbt parse failed after this change; it was rolled back. Output tail: {out[-4000:]}"]
        )


