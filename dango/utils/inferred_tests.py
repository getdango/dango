"""dango/utils/inferred_tests.py

Which generated staging data tests block a dbt build and which only warn. Key columns
(`id`, `uuid`, `key`, or a column the warehouse declares NOT NULL) keep blocking checks;
a not_null inferred from a sample of the data on any other column is warn-only, because
later data legitimately differs from the first snapshot.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

# Exact column names treated as record keys (a trailing "_id" is a foreign key, not a key).
KEY_COLUMN_NAMES = frozenset({"id", "uuid", "key"})

# Marker the generator writes on the first line of staging SQL it owns.
AUTOGEN_MARKER = "-- Auto-generated by Dango"


def warn_not_null_test() -> dict[str, Any]:
    """A ``not_null`` test that reports a warning instead of failing the build."""
    return {"not_null": {"config": {"severity": "warn"}}}


def is_key_column(name: str) -> bool:
    """True for columns named like a record key (exact ``id``/``uuid``/``key``)."""
    return name.lower() in KEY_COLUMN_NAMES


def has_not_null_test(tests: list) -> bool:
    """Check if a not_null test already exists in any form (string or dict)."""
    for test in tests:
        if test == "not_null":
            return True
        if isinstance(test, dict) and "not_null" in test:
            return True
    return False


def inferred_not_null_test(column_name: str) -> str | dict[str, Any]:
    """The test to add for a column profiled as having no nulls in the current data.

    Key columns get a blocking ``not_null``; every other column gets a warn-only one.
    """
    return "not_null" if is_key_column(column_name) else warn_not_null_test()


def is_customized_model(staging_dir: Path, model_name: str) -> bool:
    """True when the model's SQL exists and no longer carries the auto-generated marker."""
    sql_path = staging_dir / f"{model_name}.sql"
    if not sql_path.exists():
        return False
    try:
        return AUTOGEN_MARKER not in sql_path.read_text(encoding="utf-8")[:500]
    except OSError:
        return True
