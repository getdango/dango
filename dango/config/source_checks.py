"""dango/config/source_checks.py

Read-only checks over sources.yml and the staging files Dango generates for it: duplicate
source names, unknown keys in a source block, datasets that collide with the staging schema of
another source, orphaned staging files, and plain-words schema
errors for `dango source edit`. Nothing here writes or deletes anything.
"""

from __future__ import annotations

import os
import re
import shlex
from collections import Counter
from collections.abc import Iterable
from pathlib import Path, PureWindowsPath
from typing import Any, get_args

import yaml
from pydantic import AliasChoices, BaseModel, ValidationError

GENERATED_MARKER = "Auto-generated by Dango"
STAGING_DIR = Path("dbt") / "models" / "staging"

_SOURCES_FILE_RE = re.compile(r"sources_(.+)\.yml")
_STAGING_SCHEMA_RE = re.compile(r"stg_(.+)\.yml")


def duplicate_source_names(names: Iterable[Any]) -> list[str]:
    """Names used more than once, compared the way the model does (case-insensitive), sorted."""
    counts = Counter(str(name).lower() for name in names)
    return sorted(name for name, count in counts.items() if count > 1)


def duplicate_names_message(duplicates: list[str]) -> str:
    """The user-facing text for duplicate source names (names first, then how to fix it)."""
    return (
        f"Duplicate source name(s): {', '.join(duplicates)}. Source names are not case-sensitive, "
        "and two entries with the same name write to the same tables and delete each other's "
        "rows. Rename one entry in .dango/sources.yml (run 'dango source edit') and re-run."
    )


def load_raw_source_entries(project_root: Path) -> list[dict[str, Any]] | None:
    """The source blocks of sources.yml as written, or None when the file is missing or unreadable.

    Deliberately independent of the pydantic models: it still works when the file would not
    pass validation, which is exactly when a check needs to explain why.
    """
    path = project_root / ".dango" / "sources.yml"
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, yaml.YAMLError):
        return None
    if data is None:
        return []
    if not isinstance(data, dict):
        return None
    sources = data.get("sources")
    if sources is None:
        return []
    if not isinstance(sources, list):
        return None
    return [entry for entry in sources if isinstance(entry, dict)]


def entry_names(entries: Iterable[dict[str, Any]]) -> list[str]:
    """The string names of raw source entries."""
    return [e["name"] for e in entries if isinstance(e.get("name"), str)]


def _nested_model(annotation: Any) -> type[BaseModel] | None:
    for arg in get_args(annotation) or (annotation,):
        if isinstance(arg, type) and issubclass(arg, BaseModel):
            return arg
    return None


def _accepted_keys(model: type[BaseModel]) -> set[str]:
    keys: set[str] = set()
    for name, field in model.model_fields.items():
        keys.add(name)
        if field.alias:
            keys.add(field.alias)
        alias = field.validation_alias
        if isinstance(alias, str):
            keys.add(alias)
        elif isinstance(alias, AliasChoices):
            keys.update(c for c in alias.choices if isinstance(c, str))
    return keys


def unknown_source_keys(entries: Iterable[dict[str, Any]]) -> dict[str, list[str]]:
    """Keys inside a source's type block that the block's model does not know.

    Returns ``{source_name: ["local_files.file_patern", ...]}``. These load fine (extra keys
    are ignored), which is why a typo goes unnoticed without this check.
    """
    from dango.config.models import DataSource

    found: dict[str, list[str]] = {}
    for entry in entries:
        name = entry.get("name")
        if not isinstance(name, str):
            continue
        for key, value in entry.items():
            field = DataSource.model_fields.get(key) if isinstance(key, str) else None
            model = _nested_model(field.annotation) if field is not None else None
            if model is None or not isinstance(value, dict):
                continue
            accepted = _accepted_keys(model)
            found.setdefault(name, []).extend(
                f"{key}.{k}" for k in sorted(map(str, value)) if k not in accepted
            )
    return {name: keys for name, keys in found.items() if keys}


def staging_collisions(sources: Iterable[Any]) -> list[tuple[str, str, str]]:
    """``(source, other, schema)`` where *source* loads into the merge-staging schema of *other*.

    dlt writes the staging copies of a merge load into ``<dataset>_staging``; a source whose own
    schema has that name shares those tables with it. Sources are compared whether enabled or not.
    """
    from dango.config.source_datasets import schemas_of, staging_schema_of

    listed = list(sources)
    found = []
    for other in listed:
        schema = staging_schema_of(other)
        if schema is None:
            continue
        for source in listed:
            if source.name != other.name and schema in schemas_of(source):
                found.append((source.name, other.name, schema))
    return sorted(found)


def _staging_file_source(name: str, configured: set[str]) -> tuple[str, bool] | None:
    """(source the generated file belongs to, whether that source is configured), or None.

    None means the file name is not one of the shapes the generator writes.
    """
    match = _SOURCES_FILE_RE.fullmatch(name) or _STAGING_SCHEMA_RE.fullmatch(name)
    if match:
        return match.group(1), match.group(1) in configured
    if name.startswith("stg_") and name.endswith(".sql"):
        rest = name[len("stg_") : -len(".sql")]
        if "__" not in rest:
            return None
        return rest.split("__", 1)[0], any(rest.startswith(f"{n}__") for n in configured)
    return None


def find_orphaned_staging_files(project_root: Path, configured: Iterable[str]) -> list[Path]:
    """Generated staging files whose source is not in ``configured`` (project-relative paths).

    Only files carrying Dango's auto-generated marker are considered, so a hand-written model
    is never listed. Pure listing: nothing is removed.
    """
    names = {str(n).lower() for n in configured}
    staging = project_root / STAGING_DIR
    if not staging.is_dir():
        return []
    orphans: list[Path] = []
    for path in sorted(staging.iterdir(), key=lambda p: p.name):
        if not path.is_file():
            continue
        owner = _staging_file_source(path.name, names)
        if owner is None or owner[1]:
            continue
        try:
            head = path.read_text(encoding="utf-8", errors="replace")[:500]
        except OSError:
            continue
        if GENERATED_MARKER in head:
            orphans.append(STAGING_DIR / path.name)
    return orphans


def delete_command(paths: Iterable[Path], windows: bool | None = None) -> str:
    """The shell command that deletes ``paths`` (project-relative), for this platform.

    On Windows it is one ``del "<path>"`` per line: PowerShell's ``del`` (Remove-Item) takes a
    single positional path, and the quoted one-file form also runs in cmd.exe.
    """
    if windows is None:
        windows = os.name == "nt"
    if windows:
        return "\n".join(f'del "{PureWindowsPath(p)}"' for p in paths)
    return "rm " + " ".join(shlex.quote(p.as_posix()) for p in paths)


def describe_sources_errors(data: Any) -> list[str]:
    """Plain-words problems that would stop the loader from using ``data`` as sources.yml.

    Validates with the same model and version rule the loader applies; an empty list means
    the loader would accept it.
    """
    from dango.config.loader import ConfigLoader
    from dango.config.models import SourcesConfig

    if data is None:
        data = {}
    if not isinstance(data, dict):
        return ["sources.yml must be a mapping with a 'sources' list."]
    try:
        config = SourcesConfig(**data)
    except ValidationError as exc:
        entries = data.get("sources") if isinstance(data.get("sources"), list) else []
        return [_describe_error(err, entries or []) for err in exc.errors()]
    except TypeError as exc:
        return [str(exc)]
    if config.version not in ConfigLoader.SUPPORTED_SOURCES_VERSIONS:
        supported = ", ".join(sorted(ConfigLoader.SUPPORTED_SOURCES_VERSIONS))
        return [f"version '{config.version}' is not supported (supported: {supported})."]
    return []


def _describe_error(err: Any, entries: list[Any]) -> str:
    loc = list(err["loc"])
    message = str(err["msg"]).removeprefix("Value error, ")
    if len(loc) >= 2 and loc[0] == "sources" and isinstance(loc[1], int):
        entry = entries[loc[1]] if loc[1] < len(entries) else None
        name = entry.get("name") if isinstance(entry, dict) else None
        where = f"source '{name}'" if name else f"source entry {loc[1] + 1}"
        field = ".".join(str(p) for p in loc[2:])
        return f"{where}, {field}: {message}" if field else f"{where}: {message}"
    field = ".".join(str(p) for p in loc)
    return f"{field}: {message}" if field else message
